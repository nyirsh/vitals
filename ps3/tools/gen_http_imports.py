#!/usr/bin/env python3
"""Writes tests/http-probe/cellhttp_imports.yml from vitals-http/src/cellhttp_exports.h: all 181
cellHttp functions Sony's libhttp exports, by NID, for PS3DK's ps3_prx_stub_library (nidgen). The
probe imports libhttp through it: PS3DK's own stub lacks some (cellHttpGetCookie, the cookie
export and import, cellHttpCookieFlush):

    tools/gen_http_imports.py"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
EXPORTS = os.path.join(ROOT, "vitals-http", "src", "cellhttp_exports.h")
OUTPUT = os.path.join(ROOT, "tests", "http-probe", "cellhttp_imports.yml")


def main():
    with open(EXPORTS) as file:
        entries = re.findall(r"CELLHTTP_EXPORT\((0x[0-9A-Fa-f]{8}), (\w+)\)", file.read())
    lines = [
        "# Generated by tools/gen_http_imports.py from vitals-http/src/cellhttp_exports.h; do not edit.",
        "# The cellHttp library as the probe imports it (ps3_prx_stub_library, tests/http-probe/CMakeLists.txt)",
        "library: cellHttp",
        "module: cellHttp_Library",
        "archive_name: probe_cellhttp",
        "version: 1",
        "exports:",
    ]
    for nid, name in entries:
        lines += [f"  - name: {name}", f"    nid: '{nid.lower()}'", f"    signature: 'int {name}(void);'"]
    with open(OUTPUT, "w") as file:
        file.write("\n".join(lines) + "\n")
    print(f"{OUTPUT}: {len(entries)} functions")


if __name__ == "__main__":
    main()
