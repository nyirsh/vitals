#!/usr/bin/env python3
"""Writes vitals-http/src/cellhttp_exports.h, the list of the functions Sony's libhttp exports in its
two libraries and in its order, and docs/libhttp-api.md, each with its NID, name, address and the
dumped modules that import it:

    tools/gen_http_exports.py <libhttp.prx> [dumps folder]

The dumps folder (default: the module's own) is searched for every .prx, and the vsh.elf in each
vsh/<cfw>/ (or the folder's own), importing cellHttp or cellHttpUtil. Names come from tools/names; the unnamed are cellHttp_<NID>."""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from nids import load_names  # noqa: E402
from prx import Prx  # noqa: E402

HEADER = os.path.join(ROOT, "vitals-http", "src", "cellhttp_exports.h")
DOCUMENT = os.path.join(ROOT, "docs", "libhttp-api.md")
LIBRARIES = ("cellHttp", "cellHttpUtil")


def callers(folder):
    """{(library, nid): [module names]} from the folder's modules' imports"""
    found = {}
    paths = [os.path.join(folder, name) for name in sorted(os.listdir(folder))
             if name.endswith(".prx") or name == "vsh.elf"]
    # The XMB comes from a custom firmware, which may patch it: one folder each, the first counted
    builds = os.path.join(folder, "vsh")
    if not any(os.path.basename(path) == "vsh.elf" for path in paths) and os.path.isdir(builds):
        paths += [os.path.join(builds, name, "vsh.elf") for name in sorted(os.listdir(builds))
                  if os.path.isfile(os.path.join(builds, name, "vsh.elf"))][:1]
    for path in paths:
        try:
            imports = Prx(path).imports()
        except (ValueError, IndexError, KeyError, OSError):
            continue
        module = os.path.basename(path).rsplit(".", 1)[0]
        for library, entries in imports:
            if library in LIBRARIES:
                for nid, _stub in entries:
                    found.setdefault((library, nid), []).append(module)
    return found


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    path = sys.argv[1]
    folder = sys.argv[2] if len(sys.argv) == 3 else os.path.dirname(os.path.abspath(path))
    prx = Prx(path)
    module, attributes, version, *_ = prx.info()
    if module != "cellHttp_Library":
        sys.exit(f"{path}: not Sony's libhttp (module {module!r})")
    names = load_names()
    users = callers(folder)
    libraries = {name: (functions, entries) for name, functions, _v, entries in prx.exports() if name in LIBRARIES}
    lines = [
        "/* Generated by tools/gen_http_exports.py from Sony's libhttp.prx "
        f"({module} {version[0]}.{version[1]}, attributes 0x{attributes:x}); do not edit.",
        " * Every function its two libraries export, in Sony's order: CELLHTTP_EXPORT(nid, name) for",
        " * cellHttp, CELLHTTPUTIL_EXPORT(nid, name) for cellHttpUtil */",
        "",
    ]
    rows = []
    totals = {}
    for library in LIBRARIES:
        functions, entries = libraries[library]
        macro = "CELLHTTP_EXPORT" if library == "cellHttp" else "CELLHTTPUTIL_EXPORT"
        named = 0
        for nid, address in entries[:functions]:
            name = names.get(nid)
            named += name is not None
            name = name or f"{library}_{nid:08X}"
            lines.append(f"{macro}(0x{nid:08X}, {name})")
            who = users.get((library, nid), [])
            rows.append((library, nid, name, address, ", ".join(who) if who else "-"))
        totals[library] = (functions, named)
    os.makedirs(os.path.dirname(HEADER), exist_ok=True)
    with open(HEADER, "w") as file:
        file.write("\n".join(lines) + "\n")
    importers = sorted({m for who in users.values() for m in who})
    document = [
        f"# Sony's PS3 libhttp ({module} {version[0]}.{version[1]}, firmware 4.93): its exports",
        "",
        "Generated by [tools/gen_http_exports.py](../tools/gen_http_exports.py). Two libraries: "
        + ", ".join(f"`{lib}` with {n} functions ({k} named)" for lib, (n, k) in totals.items())
        + ". Names from RPCS3's module table or found by hashing (tools/names); the others are to be named "
        "from what their code does. \"Address\" is the function descriptor in Sony's module; \"Callers\" are "
        "the modules of the 4.93 dumps that import it (games call them too): "
        + ", ".join(importers) + ".",
        "",
        "| Library | NID | Name | Address | Callers |",
        "| --- | --- | --- | --- | --- |",
    ]
    for library, nid, name, address, who in sorted(rows, key=lambda r: (r[0], r[2].lower())):
        document.append(f"| {library} | `{nid:08X}` | `{name}` | `{address:08X}` | {who} |")
    with open(DOCUMENT, "w") as file:
        file.write("\n".join(document) + "\n")
    print(f"{HEADER}: " + ", ".join(f"{lib} {n} ({k} named)" for lib, (n, k) in totals.items()))
    print(f"{DOCUMENT}: {len(rows)} rows, callers from {len(importers)} modules")


if __name__ == "__main__":
    main()
