#!/usr/bin/env python3
"""Writes vitals-ssl/src/cellssl_exports.h, the list of the functions Sony's libssl exports, in its order:
one CELLSSL_EXPORT(nid, name) line each, named from tools/names (cellSsl_<NID> where unnamed). The
module's export table and its stubs are generated from it, so the replacement exports exactly
Sony's 114 NIDs. Run against a decrypted libssl.prx (the file itself isn't in the repository):

    tools/gen_ssl_exports.py ../dumps/ps3/4.93-cex/libssl.prx"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from nids import load_names  # noqa: E402
from prx import Prx  # noqa: E402

OUTPUT = os.path.join(HERE, "..", "vitals-ssl", "src", "cellssl_exports.h")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    prx = Prx(sys.argv[1])
    module, attributes, version, *_ = prx.info()
    library = [entry for entry in prx.exports() if entry[0] == "cellSsl"]
    if module != "cellSsl_Library" or len(library) != 1:
        sys.exit(f"{sys.argv[1]}: not Sony's libssl (module {module!r})")
    _name, functions, _variables, entries = library[0]
    names = load_names()
    lines = [
        "/* Generated by tools/gen_ssl_exports.py from Sony's libssl.prx "
        f"({module} {version[0]}.{version[1]}, attributes 0x{attributes:x}); do not edit.",
        " * Every function the cellSsl library exports, in Sony's order: CELLSSL_EXPORT(nid, name) */",
        "",
    ]
    for nid, _address in entries[:functions]:
        lines.append(f"CELLSSL_EXPORT(0x{nid:08X}, {names.get(nid, f'cellSsl_{nid:08X}')})")
    with open(OUTPUT, "w") as file:
        file.write("\n".join(lines) + "\n")
    print(f"{OUTPUT}: {functions} functions")


if __name__ == "__main__":
    main()
