#!/usr/bin/env python3
"""Writes vitals-http/cellssl_imports.yml from vitals-ssl/src/cellssl_exports.h: every function Sony's
libssl exports (vitals' does the same), with its NID, for PS3DK's ps3_prx_stub_library (nidgen), so
vitals' libhttp imports libssl as Sony's libhttp does, by NID:

    tools/gen_ssl_imports.py"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
EXPORTS = os.path.join(ROOT, "vitals-ssl", "src", "cellssl_exports.h")
OUTPUT = os.path.join(ROOT, "vitals-http", "cellssl_imports.yml")


def main():
    with open(EXPORTS) as file:
        entries = re.findall(r"CELLSSL_EXPORT\((0x[0-9A-Fa-f]{8}), (\w+)\)", file.read())
    lines = [
        "# Generated by tools/gen_ssl_imports.py from vitals-ssl/src/cellssl_exports.h; do not edit.",
        "# The cellSsl library as vitals' libhttp imports it (ps3_prx_stub_library, vitals-http/CMakeLists.txt)",
        "library: cellSsl",
        "module: cellSsl_Library",
        "archive_name: vitals_cellssl",
        "version: 1",
        "exports:",
    ]
    for nid, name in entries:
        lines += [f"  - name: {name}", f"    nid: '{nid.lower()}'", f"    signature: 'int {name}(void);'"]
    with open(OUTPUT, "w") as file:
        file.write("\n".join(lines) + "\n")
    print(f"{OUTPUT}: {len(entries)} functions")


if __name__ == "__main__":
    main()
